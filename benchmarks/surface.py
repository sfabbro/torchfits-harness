"""Public surface of the installed torchfits, and how much of it we exercise.

The harness verifies behaviour, but nothing stops a new torchfits release from
shipping a symbol that no replay, parity or benchmark suite ever touches. This
module introspects the *installed* distribution (the harness never imports
torchfits source), records every public callable, and matches those names
against the harness test sources.

Matching is by name, not by execution, so it answers "is this surface even
mentioned by a test?" — a cheap, stable gate. ``pytest --cov`` answers the
stronger question and lives in ``scripts/coverage_report.py``.
"""

from __future__ import annotations

import inspect
import json
import re
from dataclasses import dataclass
from pathlib import Path
from types import ModuleType
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SURFACE_DIR = ROOT / "benchmarks" / "surface"
REGISTRY_PATH = SURFACE_DIR / "public_surface.json"
EXEMPTIONS_PATH = SURFACE_DIR / "exemptions.json"
TESTS_DIR = ROOT / "tests"

# Attributes that carry no behavioural promise of their own.
_IGNORED_ATTRS = {"__all__", "__version__", "__author__", "__doc__"}


@dataclass(frozen=True, order=True)
class Entry:
    """One public symbol: ``path`` is dotted from the package root."""

    path: str
    kind: str

    def as_dict(self) -> dict[str, str]:
        return {"path": self.path, "kind": self.kind}


def _public_names(module: ModuleType) -> list[str]:
    names = getattr(module, "__all__", None)
    if names is None:
        names = [n for n in dir(module) if not n.startswith("_")]
    return sorted({n for n in names if n not in _IGNORED_ATTRS})


def _submodules(package: ModuleType) -> dict[str, ModuleType]:
    return {
        name: value
        for name in _public_names(package)
        if isinstance(value := getattr(package, name, None), ModuleType)
    }


def _class_members(cls: type, prefix: str) -> list[Entry]:
    """Members *defined on* ``cls``; inherited ones belong to their own class.

    Skipping inherited attributes keeps ``torch.nn.Module`` (``state_dict``,
    ``add_module``…) and the transform protocol out of the registry — they are
    PyTorch's or the base class' surface, not this class'.
    """
    entries: list[Entry] = []
    for name, value in vars(cls).items():
        if name.startswith("_") or name in _IGNORED_ATTRS:
            continue
        if isinstance(value, property):
            kind = "property"
        elif isinstance(value, (staticmethod, classmethod)):
            kind = "method"
        elif inspect.isfunction(value) or inspect.ismethoddescriptor(value):
            kind = "method"
        else:
            continue
        entries.append(Entry(f"{prefix}.{name}", kind))
    return entries


def collect() -> list[Entry]:
    """Every public symbol of the installed torchfits, sorted."""
    import torchfits

    entries: set[Entry] = set()
    modules: dict[str, ModuleType] = {"torchfits": torchfits}
    for name, module in _submodules(torchfits).items():
        modules[f"torchfits.{name}"] = module

    for module_name, module in modules.items():
        for name in _public_names(module):
            value: Any = getattr(module, name, None)
            if isinstance(value, ModuleType) or value is None:
                continue
            if inspect.isclass(value):
                entries.add(Entry(f"{module_name}.{name}", "class"))
                entries.update(_class_members(value, f"{module_name}.{name}"))
            elif inspect.isfunction(value):
                entries.add(Entry(f"{module_name}.{name}", "function"))
            elif inspect.ismodule(value):  # pragma: no cover - defensive
                continue
            else:
                entries.add(Entry(f"{module_name}.{name}", "attribute"))
    return sorted(entries)


def load_registry() -> list[Entry]:
    payload = json.loads(REGISTRY_PATH.read_text(encoding="utf-8"))
    return sorted(Entry(**item) for item in payload["entries"])


def dump_registry(entries: list[Entry]) -> None:
    SURFACE_DIR.mkdir(parents=True, exist_ok=True)
    payload = {
        "comment": (
            "Generated by `pixi run surface-report --update`; do not edit by "
            "hand. Regenerate after a torchfits upgrade."
        ),
        "entries": [entry.as_dict() for entry in entries],
    }
    REGISTRY_PATH.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")


def load_exemptions() -> dict[str, str]:
    """Symbols the harness deliberately never exercises, with a reason."""
    if not EXEMPTIONS_PATH.exists():
        return {}
    payload = json.loads(EXEMPTIONS_PATH.read_text(encoding="utf-8"))
    return payload["exempt"]


def _test_sources() -> dict[Path, str]:
    return {
        path: path.read_text(encoding="utf-8", errors="ignore")
        for path in sorted(TESTS_DIR.glob("test_*.py"))
    }


def exercised(entries: list[Entry]) -> dict[Entry, list[str]]:
    """Map each entry to the test files whose source mentions it.

    A dotted path is matched on its last segment (``TableHDU.write`` on
    ``write``) because tests rarely spell out owners; root exports are matched
    on the full name. Names shorter than three characters must appear as a full
    word, since e.g. ``to`` would otherwise match prose.
    """
    sources = _test_sources()
    hits: dict[Entry, list[str]] = {}
    for entry in entries:
        leaf = entry.path.rsplit(".", 1)[-1]
        pattern = re.compile(rf"\b{re.escape(leaf)}\b" if len(leaf) > 2 else re.escape(leaf))
        hits[entry] = [
            path.relative_to(ROOT).as_posix()
            for path, text in sources.items()
            if pattern.search(text)
        ]
    return hits


def report(entries: list[Entry]) -> tuple[list[Entry], dict[Entry, list[str]]]:
    """Return (unexercised entries that are not exempt, per-entry test files)."""
    exemptions = load_exemptions()
    hits = exercised(entries)
    missing = [entry for entry in entries if not hits[entry] and entry.path not in exemptions]
    return missing, hits


def stale_exemptions(entries: list[Entry]) -> list[str]:
    """Exemption keys that no longer name a live symbol."""
    known = {entry.path for entry in entries}
    return sorted(set(load_exemptions()) - known)
