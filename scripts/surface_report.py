#!/usr/bin/env python
"""Report how much of the installed torchfits public surface the harness covers.

    pixi run surface-report           # summary; exits 1 on uncovered symbols
    pixi run surface-update           # regenerate the tracked registry
    pixi run surface-report --markdown docs/public-surface.md

Matching is by name against ``tests/test_*.py`` (see ``benchmarks/surface.py``),
so this is a floor, not a line-coverage substitute: `pixi run coverage-python`
answers how much of the code runs, this answers whether the *symbol* is
mentioned at all.
"""

from __future__ import annotations

import argparse
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from benchmarks import surface  # noqa: E402


def _namespace(path: str) -> str:
    parts = path.split(".")
    # torchfits.table.read -> torchfits.table; torchfits.read -> torchfits
    return ".".join(parts[:2]) if len(parts) > 2 else parts[0]


def _summary(entries: surface.Entry, hits: dict[surface.Entry, list[str]]) -> str:
    covered = sum(1 for entry in entries if hits[entry])
    total = len(entries)
    share = 100.0 * covered / total if total else 0.0
    lines = [f"public surface: {covered}/{total} exercised ({share:.1f}%)"]
    counts: Counter[str] = Counter()
    covered_per: Counter[str] = Counter()
    for entry in entries:
        ns = _namespace(entry.path)
        counts[ns] += 1
        if hits[entry]:
            covered_per[ns] += 1
    width = max(len(ns) for ns in counts) if counts else 0
    for ns in sorted(counts):
        lines.append(
            f"  {ns:<{width}}  {covered_per[ns]:>3}/{counts[ns]:<3} "
            f"({100.0 * covered_per[ns] / counts[ns]:.0f}%)"
        )
    return "\n".join(lines)


def _markdown(entries: surface.Entry, missing: list[surface.Entry], hits: dict) -> str:
    exemptions = surface.load_exemptions()
    lines = [
        "# Public surface coverage",
        "",
        "Generated by `pixi run surface-update`; do not edit by hand.",
        "`benchmarks/surface/public_surface.json` is the tracked registry, and",
        "`tests/test_public_surface.py` fails when that registry drifts from the",
        "installed wheel or a symbol appears in no test.",
        "",
        "| Namespace | Exercised | Total |",
        "|---|---:|---:|",
    ]
    counts: Counter[str] = Counter()
    covered_per: Counter[str] = Counter()
    for entry in entries:
        ns = _namespace(entry.path)
        counts[ns] += 1
        if hits[entry]:
            covered_per[ns] += 1
    for ns in sorted(counts):
        lines.append(f"| `{ns}` | {covered_per[ns]} | {counts[ns]} |")
    lines += ["", f"**Total: {len(entries)} symbols, {len(missing)} unexercised.**", ""]
    if exemptions:
        lines += ["## Deliberate exemptions", "", "| Symbol | Reason |", "|---|---|"]
        for path, reason in sorted(exemptions.items()):
            lines.append(f"| `{path}` | {reason} |")
        lines.append("")
    if missing:
        lines += ["## Unexercised", ""]
        lines += [f"- `{entry.path}` ({entry.kind})" for entry in missing]
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--update", action="store_true", help="regenerate the tracked registry"
    )
    parser.add_argument("--markdown", metavar="PATH", help="also write a report here")
    parser.add_argument(
        "--quiet", action="store_true", help="print only unexercised symbols"
    )
    args = parser.parse_args()

    entries = surface.collect()
    if args.update:
        surface.dump_registry(entries)
        print(f"wrote {surface.REGISTRY_PATH.relative_to(surface.ROOT)}")

    missing, hits = surface.report(entries)
    if not args.quiet:
        print(_summary(entries, hits))
    if args.markdown:
        target = Path(args.markdown)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(_markdown(entries, missing, hits), encoding="utf-8")
        print(f"wrote {target}")
    if missing:
        print(f"\n{len(missing)} public symbols no test mentions:", file=sys.stderr)
        for entry in missing:
            print(f"  {entry.kind:9} {entry.path}", file=sys.stderr)
        print(
            "Add a test, or record the symbol under "
            f"{surface.EXEMPTIONS_PATH.relative_to(surface.ROOT)} with a reason.",
            file=sys.stderr,
        )
        return 1
    if not args.quiet:
        print("all public symbols are exercised")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
